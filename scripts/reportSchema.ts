/**
 * JSON Schema of the JSON report (Reports → Export JSON, `toJsonReport` in src/core/report.ts), written
 * to docs/guide/report.schema.json by scripts/guide.ts (`npm run guide:sync`; guide:check verifies).
 * Error codes and their meanings come from src/core/errors.ts, so the schema cannot drift from them.
 * The suite report (`toSuiteJson`, M4.4) goes to docs/guide/suite-report.schema.json with the same run defs.
 */
import { ERROR_CODES, ERROR_CODE_LIST } from '../src/core/errors';
import { REPORT_SCHEMA_PATH, REPORT_SCHEMA_VERSION, SUITE_REPORT_SCHEMA_PATH, SUITE_REPORT_SCHEMA_VERSION } from '../src/core/report';
import { TRIGGER_LABELS } from '../src/core/runs';
import type { RunStatus, StepStatus } from '../src/core/runs';

const RUN_STATUSES = ['running', 'passed', 'failed', 'cancelled', 'interrupted'] as const satisfies readonly RunStatus[];
const STEP_STATUSES = ['running', 'passed', 'failed', 'handled', 'skipped'] as const satisfies readonly StepStatus[];

const payload = { type: 'object', description: 'Data as it left or entered the block (secrets masked). Large payloads become {"$preview": "…", "$size": n}.' };
const isoTime = { type: 'string', format: 'date-time' };
const rect = (description: string) => ({
  type: 'object', required: ['x', 'y', 'width', 'height'], description,
  properties: { x: { type: 'number' }, y: { type: 'number' }, width: { type: 'number' }, height: { type: 'number' } },
});

function schema() {
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `https://raw.githubusercontent.com/akibh-dev/blockflow/main/${REPORT_SCHEMA_PATH}`,
    title: 'BlockFlow JSON report',
    description: `What Reports → Export JSON writes (schemaVersion ${REPORT_SCHEMA_VERSION}). Generated by scripts/reportSchema.ts.`,
    type: 'object',
    required: ['schemaVersion', 'generatedAt', 'summary', 'runs'],
    properties: {
      $schema: { type: 'string' },
      schemaVersion: { const: REPORT_SCHEMA_VERSION },
      generatedAt: isoTime,
      summary: {
        type: 'object',
        required: ['total', 'passed', 'failed', 'other', 'durationMs'],
        properties: {
          total: { type: 'integer' },
          passed: { type: 'integer' },
          failed: { type: 'integer', description: 'Failed and interrupted runs.' },
          other: { type: 'integer', description: 'Cancelled or still running.' },
          durationMs: { type: 'number' },
        },
      },
      runs: { type: 'array', items: { $ref: '#/$defs/run' } },
    },
    $defs: {
      run: {
        type: 'object',
        required: ['id', 'workflowId', 'workflowName', 'trigger', 'status', 'startedAt', 'steps'],
        properties: {
          id: { type: 'string' },
          workflowId: { type: 'string' },
          workflowName: { type: 'string' },
          trigger: { enum: Object.keys(TRIGGER_LABELS) },
          status: { enum: RUN_STATUSES },
          startedAt: isoTime,
          endedAt: isoTime,
          steps: { type: 'array', items: { $ref: '#/$defs/step' } },
          droppedSteps: { type: 'integer', description: 'Steps not kept because the run was very long.' },
          error: { type: 'string', description: 'Why the run failed or stopped, in one line.' },
          parentRunId: { type: 'string', description: 'Set when a Run Workflow block started this run.' },
          usedDebugger: { type: 'boolean', description: 'This run acquired a Chromium debugger session (CDP).' },
          mode: {
            type: 'object', description: 'M5: how the run was started: traced, debug run, or Run from here (the node it started at).',
            properties: { trace: { type: 'boolean' }, debug: { type: 'boolean' }, startedAt: { type: 'string' } },
          },
        },
      },
      step: {
        type: 'object',
        required: ['nodeId', 'blockType', 'status', 'startedAt', 'attempts'],
        properties: {
          nodeId: { type: 'string', description: 'Id of the node in the stored workflow.' },
          sourceId: { type: 'string', description: 'Id of the node in the file it was imported from, when it differs or came from a file.' },
          blockType: { type: 'string' },
          status: { enum: STEP_STATUSES, description: 'handled = failed, but the step setting "on error" dealt with it.' },
          startedAt: isoTime,
          durationMs: { type: 'number' },
          attempts: { type: 'integer' },
          input: payload,
          output: payload,
          port: { type: 'string', description: 'The output the result was sent from.' },
          error: { type: 'string' },
          code: { $ref: '#/$defs/errorCode' },
          locator: { type: 'string', description: 'The locator the failing step used.' },
          url: { type: 'string', description: 'URL of the page when the step failed.' },
          matches: { type: 'array', maxItems: 5, items: { type: 'string' }, description: 'For locator.strict: the elements that matched, described.' },
          screenshot: { type: 'string', description: 'Id of a screenshot (not embedded in JSON).' },
          childRunId: { type: 'string', description: 'For Run Workflow: the run of the called workflow.' },
          console: {
            type: 'array', maxItems: 100, description: 'Bounded page console and exceptions, secret values masked.',
            items: { type: 'object', required: ['level', 'text', 'timestamp'], properties: { level: { type: 'string' }, text: { type: 'string', maxLength: 2000 }, timestamp: { type: 'number' }, url: { type: 'string' } } },
          },
          trace: { $ref: '#/$defs/trace' },
        },
      },
      trace: {
        type: 'object',
        description: 'M5.1 trace of a step (traced run, or the step setting `trace`). Picture ids are like `screenshot` (not embedded in JSON).',
        properties: {
          before: { type: 'string', description: 'Id of the picture taken before the block ran.' },
          after: { type: 'string', description: 'Id of the picture taken after it finished.' },
          box: rect('The element the step acted on, in CSS pixels of the viewport (the picture shows the viewport).'),
          viewport: { type: 'object', required: ['width', 'height'], properties: { width: { type: 'number' }, height: { type: 'number' } }, description: 'Viewport size in CSS pixels when `box` was measured.' },
          url: { type: 'string', description: 'Page URL after the step.' },
          network: {
            type: 'object', required: ['requests', 'failed'],
            description: 'Requests during the step, when the run already had a debugger session on the tab (metadata only).',
            properties: {
              requests: { type: 'integer' },
              failed: { type: 'integer', description: 'Failed to load, or HTTP status 400 and up.' },
              slowest: {
                type: 'array', maxItems: 3,
                items: { type: 'object', required: ['url', 'method', 'ms'], properties: { url: { type: 'string' }, method: { type: 'string' }, status: { type: 'integer' }, ms: { type: 'number' } } },
              },
            },
          },
        },
      },
      errorCode: {
        description: 'What kind of failure it was. Set whenever `error` is.',
        oneOf: ERROR_CODE_LIST.map((code) => ({ const: code, description: `${ERROR_CODES[code].meaning} Fix: ${ERROR_CODES[code].fix}` })),
      },
    },
  };
}

/** JSON Schema of the suite report (`toSuiteJson`): the suite's outcome, counts and runs (same `$defs`). */
function suiteSchema() {
  const { $defs } = schema();
  return {
    $schema: 'https://json-schema.org/draft/2020-12/schema',
    $id: `https://raw.githubusercontent.com/akibh-dev/blockflow/main/${SUITE_REPORT_SCHEMA_PATH}`,
    title: 'BlockFlow JSON suite report',
    description: `The combined JSON report of a suite run (Suites → JSON, \`suite.run\` with formats ["json"]; schemaVersion ${SUITE_REPORT_SCHEMA_VERSION}). Generated by scripts/reportSchema.ts.`,
    type: 'object',
    required: ['schemaVersion', 'generatedAt', 'suite', 'summary', 'runs'],
    properties: {
      $schema: { type: 'string' },
      schemaVersion: { const: SUITE_REPORT_SCHEMA_VERSION },
      generatedAt: isoTime,
      suite: {
        type: 'object',
        required: ['name', 'status', 'startedAt', 'finishedAt', 'skipped'],
        properties: {
          id: { type: 'string', description: 'Id of the saved suite; absent for an inline suite.' },
          name: { type: 'string' },
          status: { enum: ['passed', 'failed'], description: 'passed when every workflow ran and passed.' },
          startedAt: isoTime,
          finishedAt: isoTime,
          skipped: { type: 'array', items: { type: 'string' }, description: 'Names of workflows not run because the suite stops on failure.' },
        },
      },
      summary: {
        type: 'object',
        required: ['total', 'passed', 'failed', 'skipped', 'durationMs'],
        properties: {
          total: { type: 'integer', description: 'Workflows in the suite (run or skipped).' },
          passed: { type: 'integer' },
          failed: { type: 'integer', description: 'Runs that did not pass (failed, interrupted or cancelled).' },
          skipped: { type: 'integer' },
          durationMs: { type: 'number', description: 'Wall time of the whole suite.' },
        },
      },
      runs: { type: 'array', items: { $ref: '#/$defs/run' }, description: 'One run per workflow that ran, in suite order.' },
    },
    $defs,
  };
}

/** The files this module adds to docs/guide (name → content). */
export function reportSchemaFiles(): Record<string, string> {
  return {
    'report.schema.json': `${JSON.stringify(schema(), null, 2)}\n`,
    'suite-report.schema.json': `${JSON.stringify(suiteSchema(), null, 2)}\n`,
  };
}
